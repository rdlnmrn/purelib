// Produce a checked-in page that also works over file://, without module fetches.
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { build } from "vite"
import react from "@vitejs/plugin-react"

const root = fileURLToPath(new URL(".", import.meta.url))
const result = await build({
  configFile: false,
  root,
  plugins: [react()],
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  build: {
    write: false,
    lib: {
      entry: fileURLToPath(new URL("src/main.tsx", import.meta.url)),
      name: "CCLEssay",
      formats: ["iife"],
    },
    cssCodeSplit: false,
  },
})
const outputs = (Array.isArray(result) ? result : [result]).flatMap(r => r.output)
const scripts = outputs.filter(item => item.type === "chunk")
const styles = outputs.filter(item => item.type === "asset" && item.fileName.endsWith(".css"))
const unexpected = outputs.filter(item => item.type === "asset" && !item.fileName.endsWith(".css"))
if (scripts.length !== 1 || unexpected.length) {
  throw new Error("Static export must contain one script and inline all other assets")
}
const template = await readFile(new URL("index.html", import.meta.url), "utf8")
const favicon = await readFile(new URL("favicon.svg", import.meta.url), "utf8")
const css = styles.map(item => String(item.source)).join("\n")
const html = template
  .replace('href="./favicon.svg"', `href="data:image/svg+xml;base64,${Buffer.from(favicon).toString("base64")}"`)
  .replace("</head>", `<style>${css.replace(/<\/style/gi, "<\\/style")}</style>\n</head>`)
  .replace('<script type="module" src="/src/main.tsx"></script>',
    () => `<script>${scripts[0].code.replace(/<\/script/gi, "<\\/script")}</script>`)
  .replace('<div id="root"></div>', '<div id="root"></div><noscript>This essay requires JavaScript to display its text and figures.</noscript>')
await writeFile(new URL("static.html", import.meta.url),
  "<!-- Generated by npm run build:static; edit src/ and regenerate. -->\n" + html)
console.log("Wrote docs/ccl/static.html")
