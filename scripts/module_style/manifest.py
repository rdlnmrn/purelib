#!/usr/bin/env python3
"""Inventory and group Lean sources for reviewed module-style plans.

Regenerate with `python3 -m scripts.module_style.manifest --regenerate`; verify
with `python3 -m scripts.module_style.manifest --check`. Neither command edits
Lean sources or decides import visibility, namespace openings, or docstrings.
The pinned source revision is the base commit recorded during regeneration;
per-file hashes bind the actual working sources, including uncommitted changes.
A check retains that base revision so committing the manifest does not itself
make the manifest stale. Classification uncertainty stays in `review_needed`.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import heapq
import json
import math
from pathlib import Path
import re
import subprocess
import sys
import tomllib

from scripts.module_style import core as module_style

from scripts.paths import ROOT
OUTPUT = ROOT / 'docs/module-style/manifest.json'
GROUP_LIMIT = 32
# Reviewed generator ownership, recorded by current source markers.
GENERATED_CERTIFICATES: dict[str, str] = {}
GENERATED_MARKER = re.compile(
    r'(?im)^\s*--\s*(?:This file is generated by|Do not edit it by hand|generated by|DO NOT EDIT)\b[^\n]*')
GENERATED_PROSE = re.compile(r'(?i)generated (?:sample )?(?:certificate|data|rational|root|sample)')


def sha(data: bytes) -> str:
    """Hash the exact retained bytes of a source or manifest input."""
    return hashlib.sha256(data).hexdigest()


def load_project_inventory():
    """Load the authoritative source boundary without running its CLI."""
    from scripts.verification import modules
    return modules


def source_roots(project) -> list[str]:
    """Include the build roots, authoritative project roots, and Lean scripts."""
    config = tomllib.loads((ROOT / 'lakefile.toml').read_text())
    roots = set(project.ACTIVE_ROOTS) | {'scripts'}
    for kind in ('lean_lib', 'lean_exe'):
        for entry in config.get(kind, []):
            if entry.get('srcDir', '.') != '.':
                raise ValueError(f"review source discovery for custom srcDir: {entry['srcDir']}")
            modules = entry.get('roots', []) + entry.get('globs', [])
            if 'root' in entry:
                modules.append(entry['root'])
            roots.update(module.split('.')[0] for module in modules)
    missing = sorted(name for name in roots if not (ROOT / name).is_dir())
    if missing:
        raise ValueError(f'configured source roots are missing: {missing}')
    return sorted(roots)


def classify(path: Path, text: str, inactive: set[str]) -> tuple[str, str, str | None]:
    """Keep subject mathematics in scope and defer evidenced generator output."""
    relative = path.as_posix()
    marker = GENERATED_MARKER.search(text)
    example = path.parts[:2] == ('Purelib', 'Examples')
    if relative in inactive:
        return ('excluded-fixture', 'Inactive archive explicitly listed by scripts/project-modules.py; excluded from active source review.', None)
    if any(part.lower() in {'fixture', 'fixtures'} for part in path.parts[:-1]):
        return ('excluded-fixture', 'Dedicated fixture directory contains test inputs rather than authored production or regression modules.', None)
    if relative in GENERATED_CERTIFICATES:
        generator = GENERATED_CERTIFICATES[relative]
        if f'Generated by {generator}' not in text:
            raise ValueError(f'missing reviewed generator ownership marker: {relative}')
        return ('deferred-generated', f'Emitted regression certificate owned by {generator}; the output records that generator explicitly.', None)
    if example and marker:
        return ('deferred-generated', 'Generated example output is explicitly marked: ' + marker[0].strip(), None)
    if example and 'Generated' in path.parts:
        return ('deferred-generated', 'The Examples/.../Generated directory explicitly owns emitted certificate data or its generated assembly modules.', None)
    if marker:
        return ('authored', 'Reusable subject mathematics extracted into its mathematical owner; historical generator comments do not exclude its definitions or proofs.', None)
    if example and GENERATED_PROSE.search(text):
        return ('authored', 'Example retained in the authored set provisionally: references to generated certificates alone do not establish that this source is generated.',
                'Review generator ownership: the example mentions generated certificates/data but has no explicit generated-file marker or Generated directory.')
    if path.parts[0] == 'scripts':
        return ('authored', 'Active Lean support, checking, benchmark, or harness source; not a fixture input.', None)
    if path.parts[0] == 'Test' or path.parts[:2] == ('Purelib', 'Test'):
        return ('authored', 'Authored regression module; regression sources remain in scope, unlike dedicated fixture inputs.', None)
    if path.parts[0] in {'papers', 'formalisations'}:
        return ('authored', 'Authored publication or optional example module in an established active source root.', None)
    return ('authored', 'Authored library or example source; no explicit evidence identifies this file as an emitted certificate table.', None)


def subject(path: str) -> str:
    """Choose a stable directory subject before splitting its dependency chain."""
    parts = Path(path).parts
    if parts[0] == 'Purelib':
        return '/'.join(parts[:min(3, len(parts) - 1)])
    if parts[0] in {'papers', 'formalisations'}:
        return '/'.join(parts[:min(2, len(parts) - 1)])
    return parts[0]


def dependency_order(rows: list[dict]) -> tuple[list[str], list[str]]:
    """Order explicit project imports before consumers, retaining cycle blockers."""
    by_module = {row['module']: row['path'] for row in rows}
    dependencies = {
        row['path']: {by_module[module] for module in row['imports'] if module in by_module}
        for row in rows
    }
    consumers: dict[str, set[str]] = defaultdict(set)
    for path, parents in dependencies.items():
        for parent in parents:
            consumers[parent].add(path)
    ready = [path for path, parents in dependencies.items() if not parents]
    heapq.heapify(ready)
    ordered = []
    while ready:
        path = heapq.heappop(ready)
        ordered.append(path)
        for consumer in sorted(consumers[path]):
            dependencies[consumer].remove(path)
            if not dependencies[consumer]:
                heapq.heappush(ready, consumer)
    blocked = sorted(set(dependencies) - set(ordered))
    return ordered + blocked, blocked


def make_groups(rows: list[dict]) -> tuple[list[dict], list[str]]:
    """Partition each subject into at most 32 files ordered by dependencies."""
    ordered, cycles = dependency_order(rows)
    rank = {path: index for index, path in enumerate(ordered)}
    buckets: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for row in rows:
        buckets[row['classification'], subject(row['path'])].append(row)
    groups = []
    for (classification, owner), members in sorted(buckets.items()):
        members.sort(key=lambda row: rank[row['path']])
        group_count = math.ceil(len(members) / GROUP_LIMIT)
        # Balance the chunks instead of leaving a tiny final group.
        width, extra = divmod(len(members), group_count)
        offset = 0
        for index in range(group_count):
            chosen = members[offset:offset + width + (index < extra)]
            offset += len(chosen)
            key = f'{classification}/{owner}/{index + 1:03d}'
            for row in chosen:
                row['group'] = key
            groups.append({'id': key, 'classification': classification, 'subject': owner,
                           'count': len(chosen), 'files': [row['path'] for row in chosen]})
    return groups, cycles


def make_manifest(revision: str) -> dict:
    """Capture all sources, explicit imports, classifications, and review groups."""
    project = load_project_inventory()
    roots = source_roots(project)
    _, inactive_paths = project.discover()
    inactive = set(inactive_paths)
    paths = sorted({path.relative_to(ROOT) for root in roots for path in (ROOT / root).rglob('*.lean')})
    rows, blockers, reviews = [], [], []
    for path in paths:
        raw = (ROOT / path).read_bytes()
        text = raw.decode('utf-8')
        classification, reason, uncertainty = classify(path, text, inactive)
        imports = []
        parser_status = 'complete'
        try:
            data = module_style.inventory(text)
            imports = sorted({entry['module'] for entry in data['imports']})
        except (ValueError, KeyError, TypeError) as error:
            parser_status = 'blocked'
            blockers.append({'path': path.as_posix(), 'error': str(error)})
        row = {'path': path.as_posix(), 'source_sha256': sha(raw),
               'module': path.with_suffix('').as_posix().replace('/', '.'),
               'group': '', 'classification': classification, 'reason': reason,
               'imports': imports, 'parser_status': parser_status}
        rows.append(row)
        if uncertainty:
            reviews.append({'path': row['path'], 'reason': uncertainty})
    groups, cycles = make_groups(rows)
    local_modules = {row['module'] for row in rows}
    missing = [{'path': row['path'], 'module': module}
               for row in rows for module in row['imports']
               if module.split('.')[0] in roots and module not in local_modules]
    inputs = ['lakefile.toml', 'scripts/project-modules.py', 'scripts/module_style/core.py',
              'scripts/module_style/manifest.py', *sorted(set(GENERATED_CERTIFICATES.values()))]
    return {
        'schema': 1,
        'source_revision': revision,
        'source_revision_note': 'Base commit at regeneration; individual source hashes bind the working sources, including uncommitted edits.',
        'source_roots': roots,
        'input_sha256': {path: sha((ROOT / path).read_bytes()) for path in inputs},
        'source_tree_sha256': sha(''.join(row['path'] + '\0' + row['source_sha256'] + '\n' for row in rows).encode()),
        'classification_policy': {
            'authored': 'Library subjects, publication, examples, regressions, and Lean support. Historical generated prose outside emitted example outputs is retained for review.',
            'deferred-generated': 'Explicitly marked generated example outputs, Examples/.../Generated owners, or reviewed generator-owned regression certificates; user deferred generated certificate work.',
            'excluded-fixture': 'Dedicated fixture directories and inactive archives, each with a per-file reason.',
            'uncertainty': 'Keep ambiguous sources authored and list them in review_needed; do not infer generation from a filename containing Certificate.',
        },
        'grouping': {'max_files': GROUP_LIMIT, 'order': 'Direct import dependencies first within each directory subject; balanced chunks. Groups support parallel authoring and do not assert independent build closures.'},
        'summary': {'files': len(rows), 'classes': dict(sorted(Counter(row['classification'] for row in rows).items())),
                    'groups': len(groups), 'groups_by_class': dict(sorted(Counter(group['classification'] for group in groups).items())),
                    'review_needed': len(reviews), 'parser_blockers': len(blockers)},
        'review_needed': reviews,
        'parser_blockers': blockers,
        'dependency_cycle_or_descendants': cycles,
        'unresolved_project_imports': missing,
        'groups': groups,
        'files': rows,
    }


def report(manifest: dict, show_groups: bool) -> None:
    """Print concise counts and explicit blockers without dumping source data."""
    summary = manifest['summary']
    print(f"{summary['files']} files; {summary['groups']} groups; {summary['review_needed']} classifications need review")
    for classification, count in summary['classes'].items():
        print(f"  {classification}: {count} files, {summary['groups_by_class'][classification]} groups")
    if show_groups:
        for group in manifest['groups']:
            print(f"  {group['id']}: {group['count']}")
    for blocker in manifest['parser_blockers']:
        print(f"parser blocker: {blocker['path']}: {blocker['error']}", file=sys.stderr)
    for path in manifest['dependency_cycle_or_descendants']:
        print(f'dependency cycle or blocked descendant: {path}', file=sys.stderr)
    for row in manifest['unresolved_project_imports']:
        print(f"missing project import: {row['path']}: {row['module']}", file=sys.stderr)


def main() -> int:
    """Regenerate the retained inventory or check its reproducibility."""
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--regenerate', action='store_true', help='write the manifest for current sources')
    mode.add_argument('--check', action='store_true', help='compare current sources with the retained manifest')
    parser.add_argument('--groups', action='store_true', help='also print every group and its file count')
    args = parser.parse_args()
    try:
        existing = None
        if args.check:
            existing = module_style.read_json(OUTPUT)
            revision = existing['source_revision']
            if not re.fullmatch(r'[0-9a-f]{40,64}', revision):
                raise ValueError('invalid pinned source revision')
            subprocess.run(['git', 'cat-file', '-e', revision + '^{commit}'], cwd=ROOT, check=True, capture_output=True)
        else:
            revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
        manifest = make_manifest(revision)
        report(manifest, args.groups)
        if args.check and manifest != existing:
            before = {row['path']: row['source_sha256'] for row in existing.get('files', [])}
            after = {row['path']: row['source_sha256'] for row in manifest['files']}
            changed = sorted(path for path in before.keys() | after.keys() if before.get(path) != after.get(path))
            print('manifest is stale; regenerate after reviewing changes', file=sys.stderr)
            for path in changed:
                print('  source changed: ' + path, file=sys.stderr)
            return 1
        if args.regenerate:
            module_style.atomic_write(OUTPUT, module_style.encoded(manifest))
            print('wrote ' + OUTPUT.relative_to(ROOT).as_posix())
        else:
            print('manifest matches current sources and classification rules')
        return int(bool(manifest['parser_blockers'] or manifest['dependency_cycle_or_descendants'] or manifest['unresolved_project_imports']))
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as error:
        print(f'module-style-manifest: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
